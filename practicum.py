import re

def simplify_pay_grade(pg):
    if pd.isna(pg):
        return 'Unknown'
    pg_str = str(pg).strip()

    # Check if there is a hyphenated structure like 'PA04 - 17' or 'FD04 - 17'
    # Often, the last part ('17') indicates the broad/equivalent pay band,
    # or the first number ('04') indicates the sub-grade. Let's extract both or fallback.
    match = re.search(r'\d+', pg_str)
    if match:
        # Extract the first consecutive sequence of digits as a fallback base numerical category
        return f"Grade_{int(match.group())}"

    return pg_str

