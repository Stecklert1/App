"""### Logistic Regression with L1 (Lasso) Regularization

Let's apply L1 regularization to our logistic regression model. This technique helps in feature selection by shrinking the coefficients of less important features to zero, thus simplifying the model and reducing overfitting.

We will use `Age_Group`, `Department Name`, `Gender`, `Race`, `FLSA Status`, `EEOJ Code`, `Employment Type`, `Pay Grade`, and `Years Since Position Began` as predictors for `High_Salary`.
"""

